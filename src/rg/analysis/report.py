def plot_tradeoff(cells, models) -> None:
    fig, ax = plt.subplots(figsize=(4.8, 3.6))
    for (arm, model), c in cells.items():
        x, y = c["UnsafeEp"], c["Resolved"]
        ax.errorbar(100 * x.value, 100 * y.value,
                    xerr=[[100 * (x.value - x.lo)], [100 * (x.hi - x.value)]],
                    yerr=[[100 * (y.value - y.lo)], [100 * (y.hi - y.value)]],
                    fmt=MARKERS[model], color=COLORS[arm], ms=6, capsize=2, lw=0.8)
        ax.annotate(arm, (100 * x.value, 100 * y.value), textcoords="offset points",
                    xytext=(4, 3), fontsize=7)
    ax.set_xlabel("Episodes with an executed unsafe action (%)")
    ax.set_ylabel("Episodes resolved correctly (%)")
    from matplotlib.lines import Line2D
    handles = [Line2D([], [], marker=MARKERS[m], ls="", color="k", label=MODEL_LABEL[m]
                      if m != "none" else "non-LLM") for m in ["none", *models]]
    ax.legend(handles=handles, fontsize=7, loc="lower right")
    ax.grid(alpha=0.3)
    ax.set_xlim(left=-2)
    fig.tight_layout()
    fig.savefig(FIG / "tradeoff.pdf")
    plt.close(fig)


def plot_family(F, models) -> None:
    arms = [a for a in ["A2", "A2b", "A3", "A4"] if a in set(F.arm)]
    fig, axes = plt.subplots(1, len(models), figsize=(3.6 * len(models), 2.8), squeeze=False)
    for ax, model in zip(axes[0], models, strict=False):
        g = F[F.model == model]
        w = 0.8 / max(len(arms), 1)
        for i, arm in enumerate(arms):
            h = g[g.arm == arm].set_index("family").reindex(list("ABCDEFGH"))
            ax.bar(np.arange(8) + i * w, 100 * h.unsafe_ep.fillna(0), w, color=COLORS[arm],
                   label=arm)
        ax.set_xticks(np.arange(8) + w * (len(arms) - 1) / 2, list("ABCDEFGH"))
        ax.set_title(MODEL_LABEL[model], fontsize=9)
        ax.set_ylabel("Unsafe episodes (%)")
        ax.set_xlabel("Fault family")
        ax.grid(alpha=0.3, axis="y")
    axes[0][0].legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(FIG / "family.pdf")
    plt.close(fig)


def plot_ablation(rows) -> None:
    models = list(dict.fromkeys(r["model"] for r in rows))
    fig, axes = plt.subplots(1, 2, figsize=(7.0, 2.6))
    w = 0.8 / max(len(models), 1)
    for j, model in enumerate(models):
        rs = [r for r in rows if r["model"] == model and r["arm"] != "A3"]
        xs = np.arange(len(rs)) + j * w
        for ax, key in ((axes[0], "d_unsafe"), (axes[1], "d_res")):
            vals = [100 * (r[key].value if r[key] else 0) for r in rs]
            err = [[100 * (r[key].value - r[key].lo) if r[key] else 0 for r in rs],
                   [100 * (r[key].hi - r[key].value) if r[key] else 0 for r in rs]]
            ax.bar(xs, vals, w, yerr=err, capsize=2, label=MODEL_LABEL[model],
                   color=["#1976d2", "#64b5f6"][j % 2])
            ax.set_xticks(np.arange(len(rs)) + w * (len(models) - 1) / 2,
                          [r["arm"][-2:] for r in rs])
            ax.axhline(0, color="k", lw=0.6)
            ax.grid(alpha=0.3, axis="y")
    axes[0].set_ylabel("$\\Delta$ unsafe episodes (pp)")
    axes[1].set_ylabel("$\\Delta$ resolved (pp)")
    axes[0].set_xlabel("Check removed")
    axes[1].set_xlabel("Check removed")
    axes[0].legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(FIG / "ablation.pdf")
    plt.close(fig)


