def complete_blocks(E: pd.DataFrame, S: pd.DataFrame, models: list[str]):
    """Per model, keep only (scenario, seed) blocks present in every main LLM arm that ran
    (and, for ablations, in A3 and every ablation arm), so all comparisons are paired on
    the same episodes. Non-LLM arms are untouched."""
    keep = pd.Series(True, index=E.index)
    blocks = {}
    for model in models:
        for group in (LLM_ARMS, ["A3", *ABLATIONS]):
            present = [a for a in group if ((E.arm == a) & (E.model == model)).any()]
            if not present:
                continue
            sets = [set(map(tuple, E[(E.arm == a) & (E.model == model)][["scenario_id", "seed"]]
                            .itertuples(index=False))) for a in present]
            common = set.intersection(*sets)
            if group is LLM_ARMS:
                blocks[model] = common
            for a in present:
                if a == "A3" and group is not LLM_ARMS:
                    continue
                m = (E.arm == a) & (E.model == model)
                ok = E[m].apply(lambda r, c=common: (r.scenario_id, r.seed) in c, axis=1)
                keep[m] = ok
    E = E[keep].copy()
    S = S[S.episode_id.isin(set(E.episode_id))].copy()
    return E, S, blocks


ARM_TAG = {"A0": "Azero", "A1": "Aone", "A1g": "Aoneg", "A2": "Atwo", "A2b": "Atwob",
           "A3": "Athree", "A4": "Afour", "A5-C1": "AblOne", "A5-C2": "AblTwo",
           "A5-C3": "AblThree", "A5-C4": "AblFour", "A5-C5": "AblFive", "A5-C6": "AblSix"}
MODEL_TAG = {"none": "Base", "llama3.2-3b": "Llama", "qwen2.5-7b": "Qwen"}


MOCK_TAG = {"correct": "Mcorr", "hallucinator": "Mhall", "over_reacher": "Mover",
            "oscillator": "Mosc", "injection_follower": "Minj"}


def irr_numbers() -> list[tuple[str, str]]:
    """Inter-rater macros: sample size always, kappa only once every row is rated."""
    sheet, key = DER / "irr_sheet.csv", DER / "irr_key.csv"
    if not (sheet.exists() and key.exists()):
        return []
    from rg.analysis.irr import kappa
    j = pd.read_csv(sheet).merge(pd.read_csv(key), on="row")
    out = [("IrrRows", str(len(j)))]
    rated = j[j.rater_unsafe.astype(str).str.strip().isin(["0", "1", "0.0", "1.0"])]
    if len(rated) == len(j):
        r = rated.rater_unsafe.astype(float).astype(int)
        u = rated.unsafe.astype(int)
        out += [("IrrKappa", f"{kappa(r, u):.2f}"), ("IrrAgree", f"{100 * (r == u).mean():.0f}")]
    return out


def behaviour(S: pd.DataFrame, models: list[str]) -> list[tuple[str, str]]:
    """Counts the results prose cites: what the model proposes, how often it repeats a
    blocked action, whether feedback changes the retry, and what the gate blocks that is
    neither unsafe nor declared-correct."""
    out = []
    for model in models:
        t = MODEL_TAG[model]
        m = S[S.model == model]
        a2 = m[m.arm == "A2"]
        out.append((f"PropsAtwo{t}", str(len(a2))))
        out.append((f"DiagAtwo{t}", str(int((a2.action == "gather_diagnostics").sum()))))
        out.append((f"DiagShareAtwo{t}",
                    f"{100 * (a2.action == 'gather_diagnostics').mean():.0f}"))
        main = m[m.arm.isin(LLM_ARMS)]
        out.append((f"Escalations{t}", str(int((main.action == "escalate_to_human").sum()))))
        for arm in ("A3", "A4"):
            g = m[m.arm == arm].sort_values(["episode_id", "step", "attempt"])
            tot = rep = 0
            for _, e in g.groupby("episode_id"):
                seen: set = set()
                for r in e.itertuples():
                    if r.blocked:
                        tot += 1
                        rep += r.key in seen
                        seen.add(r.key)
            out.append((f"Blocked{ARM_TAG[arm]}{t}", str(tot)))
            out.append((f"RepeatBlocked{ARM_TAG[arm]}{t}", str(rep)))
        g = m[m.arm == "A4"].sort_values(["episode_id", "step", "attempt"]).to_dict("records")
        same = diff = 0
        for prev, r in zip(g, g[1:], strict=False):
            if (prev["episode_id"] == r["episode_id"] and prev["step"] == r["step"]
                    and prev["blocked"] and r["attempt"] == prev["attempt"] + 1):
                same += r["key"] == prev["key"]
                diff += r["key"] != prev["key"]
        out.append((f"RetrySame{t}", str(same)))
        out.append((f"RetryDiff{t}", str(diff)))
        out.append((f"RetryTotal{t}", str(same + diff)))
        a3 = m[(m.arm == "A3") & m.blocked]
        neu = a3[~a3.unsafe & ~a3.correct]
        out.append((f"NeutralBlocks{t}", str(len(neu))))
        out.append((f"NeutralBlockEps{t}", str(neu.episode_id.nunique())))
        out.append((f"UnsafeBlocks{t}", str(int(a3.unsafe.sum()))))
        words = {"C1": "One", "C2": "Two", "C3": "Three", "C4": "Four", "C5": "Five", "C6": "Six"}
        ub = a3[a3.unsafe]
        for chk, w in words.items():
            out.append((f"AttrFires{w}{t}", str(int(ub.failed.apply(lambda f, c=chk: c in f).sum()))))
            out.append((f"AttrSole{w}{t}", str(int(ub.failed.apply(lambda f, c=chk: f == [c]).sum()))))
        inj = m[(m.arm == "A3") & m.inj & m.blocked & m.irreversible]
        x = m[(m.calls > 0) & (m.cache_hits == 0) & (m.latency_s > 0)]
        out.append((f"SecPerCall{t}", f"{(x.latency_s / x.calls).median():.0f}" if len(x) else "--"))
        out.append((f"InjMinChecks{t}", str(int(inj.failed.apply(len).min())) if len(inj) else "--"))
    return out


def write_numbers(cells, P, inj_rows, ab_rows, E, blocks, cells_m=None) -> None:
    """paper/numbers.tex: one macro per number quoted in the text (regenerated, never edited)."""
    out = ["% generated by rg analyze -- do not edit", ""]

    def put(name: str, est) -> None:
        if est is None or np.isnan(est.value):
            return
        out.append(f"\\newcommand{{\\{name}}}{{{100 * est.value:.1f}}}")
        out.append(f"\\newcommand{{\\{name}CI}}{{[{100 * est.lo:.1f}, {100 * est.hi:.1f}]}}")

    for (m, gated), c in (cells_m or {}).items():
        t = MOCK_TAG[m] + ("Gated" if gated else "Ungated")
        for k in ("UnsafeEp", "Resolved", "CatEp", "EUR"):
            put(k + t, c.get(k))
    for (arm, model), c in cells.items():
        t = ARM_TAG[arm] + MODEL_TAG[model]
        for k in ("PUR", "EUR", "UnsafeEp", "CatEp", "Resolved", "Recovered", "OverReach",
                  "EscP", "EscR", "Oscillation", "FBR", "BlockedCorrect"):
            put(k + t, c.get(k))
        out.append(f"\\newcommand{{\\Episodes{t}}}{{{c['episodes']}}}")
        out.append(f"\\newcommand{{\\Calls{t}}}{{{c['calls_ep']:.1f}}}")
    for _, r in P.iterrows():
        metric = {"unsafe episode": "Unsafe", "resolved": "Res", "catastrophic episode": "Cat"}[r.metric]
        t = f"Diff{metric}{ARM_TAG[r.a]}{ARM_TAG[r.b]}{MODEL_TAG[r.model]}"
        out.append(f"\\newcommand{{\\{t}}}{{{100 * r['diff']:+.1f}}}")
        out.append(f"\\newcommand{{\\{t}CI}}{{[{100 * r['lo']:+.1f}, {100 * r['hi']:+.1f}]}}")
        pv = "p<10^{-4}" if r.p < 1e-4 else f"p={r.p:.2g}"
        out.append(f"\\newcommand{{\\{t}P}}{{${pv}$}}")
        out.append(f"\\newcommand{{\\{t}Gain}}{{{int(r.n01)}}}")
        out.append(f"\\newcommand{{\\{t}Loss}}{{{int(r.n10)}}}")
    for r in inj_rows:
        t = ARM_TAG[r["arm"]] + MODEL_TAG[r["model"]]
        put("InjProp" + t, r["proposed"])
        put("InjExec" + t, r["executed"])
    for r in ab_rows:
        if r["arm"] == "A3":
            continue
        t = ARM_TAG[r["arm"]] + MODEL_TAG[r["model"]]
        put("Osc" + t, r["osc"])
        if r["d_unsafe"] is not None:
            out.append(f"\\newcommand{{\\DUnsafe{t}}}{{{100 * r['d_unsafe'].value:+.1f}}}")
        if r["d_res"] is not None:
            out.append(f"\\newcommand{{\\DRes{t}}}{{{100 * r['d_res'].value:+.1f}}}")
    for model, b in ((m, b) for m, b in blocks.items() if m in set(E.model)):
        t = MODEL_TAG[model]
        out.append(f"\\newcommand{{\\Blocks{t}}}{{{len(b)}}}")
        out.append(f"\\newcommand{{\\Seeds{t}}}{{{len({s for _, s in b})}}}")
    abl = E[E.arm.isin(ABLATIONS)]
    for model in set(abl.model):
        out.append(f"\\newcommand{{\\AblEpisodes{MODEL_TAG[model]}}}"
                   f"{{{len(abl[(abl.model == model) & (abl.arm == 'A5-C1')])}}}")
    out.append(f"\\newcommand{{\\EpisodesTotal}}{{{len(E):,}}}".replace(",", "{,}"))
    (ROOT / "paper" / "numbers.tex").write_text("\n".join(out) + "\n")


def _p(p) -> str:
    return "--" if p is None else f"p={p:.2g}"


